-- Example binds, see https://wiki.hypr.land/configuring/core/binds/ for more

local mainMod = "Alt_L" -- Sets "Windows" key as main modifier

--fakefullscreen bind
hl.bind(mainMod .. " + SHIFT + F", hl.dsp.window.fullscreen_state({
	action = "toggle",
	internal = 0,
	client = 2
}))
hl.bind(mainMod .. " + F", hl.dsp.window.fullscreen({
	action = "toggle",
	mode = "fullscreen",
}))
hl.bind(mainMod .. " + SHIFT + Return", hl.dsp.exec_cmd("foot tmux"))
hl.bind(mainMod .. " + SHIFT + C", hl.dsp.window.close())
hl.bind(mainMod .. " + SHIFT + Q", hl.dsp.exec_cmd("command -v hyprshutdown >/dev/null 2>&1 && hyprshutdown || hyprctl dispatch 'hl.dsp.exit()'"))
hl.bind(mainMod .. " + SHIFT + R", hl.dsp.exec_cmd("hyprctl switchxkblayout 'semico---usb-gaming-keyboard-' next"))
hl.bind(mainMod .. " + SHIFT + SPACE", hl.dsp.window.float({ action = "toggle" }))
hl.bind(mainMod .. " + P", hl.dsp.exec_cmd("hyprlauncher"))
hl.bind(mainMod .. " + Return", hl.dsp.layout("swapwithmaster"))

-- Move focus with mainMod + arrow keys
hl.bind(mainMod .. " + left",  hl.dsp.focus({ direction = "left" }))
hl.bind(mainMod .. " + right", hl.dsp.focus({ direction = "right" }))
hl.bind(mainMod .. " + up",    hl.dsp.focus({ direction = "up" }))
hl.bind(mainMod .. " + down",  hl.dsp.focus({ direction = "down" }))


-- Move focus vim-like
hl.bind(mainMod .. " + L",  hl.dsp.focus({ direction = "left" }))
hl.bind(mainMod .. " + H", hl.dsp.focus({ direction = "right" }))
hl.bind(mainMod .. " + K",    hl.dsp.focus({ direction = "up" }))
hl.bind(mainMod .. " + J",  hl.dsp.focus({ direction = "down" }))

-- Switch workspaces with mainMod + [0-9]
-- Move active window to a workspace with mainMod + SHIFT + [0-9]
for i = 1, 10 do
    local key = i % 10 -- 10 maps to key 0
    hl.bind(mainMod .. " + " .. key,             hl.dsp.focus({ workspace = i}))
    hl.bind(mainMod .. " + SHIFT + " .. key,     hl.dsp.window.move({ workspace = i }))
end

